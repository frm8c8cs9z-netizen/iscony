def validate_game_score(
    pair1_games,
    pair2_games,
    winning_games
):

    # --------------------------------------
    # 数値保証
    # --------------------------------------
    if (
        not isinstance(pair1_games, int)
        or not isinstance(pair2_games, int)
    ):
        return "ゲーム数は数値で入力してください。"

    # --------------------------------------
    # マイナス禁止
    # --------------------------------------
    if pair1_games < 0 or pair2_games < 0:
        return "ゲーム数にマイナスは登録できません。"

    # --------------------------------------
    # 上限超過禁止
    # --------------------------------------
    if (
        pair1_games > winning_games
        or pair2_games > winning_games
    ):
        return "ゲーム数が上限を超えています。"

    # --------------------------------------
    # 同点禁止
    # --------------------------------------
    if pair1_games == pair2_games:
        return "同点は登録できません。"

    # --------------------------------------
    # 勝者ゲーム数チェック
    # --------------------------------------
    if (
        max(pair1_games, pair2_games)
        != winning_games
    ):
        return "勝者のゲーム数が正しくありません。"

    # --------------------------------------
    # 敗者側は winning_games 未満
    # --------------------------------------
    if (
        min(pair1_games, pair2_games)
        >= winning_games
    ):
        return "敗者のゲーム数が多すぎます。"

    return None


def validate_star_score(
    pair1_legs,
    pair2_legs,
    total_legs
):

    # --------------------------------------
    # 数値保証
    # --------------------------------------
    if (
        not isinstance(pair1_legs, int)
        or not isinstance(pair2_legs, int)
    ):
        return "対戦数は数値で入力してください。"

    # --------------------------------------
    # マイナス禁止
    # --------------------------------------
    if pair1_legs < 0 or pair2_legs < 0:
        return "対戦数にマイナスは登録できません。"

    # --------------------------------------
    # 対戦数の合計が設定を超えないこと
    # --------------------------------------
    if pair1_legs + pair2_legs > total_legs:
        return "対戦数の合計が設定を超えています。"

    # --------------------------------------
    # 同点禁止
    # --------------------------------------
    if pair1_legs == pair2_legs:
        return "同点は登録できません。"

    # --------------------------------------
    # 過半数チェック
    # --------------------------------------
    # リタイア等のイレギュラー対応で、過半数に届かない星の数でも
    # 勝敗を確定させたい場合(例: 3対戦中、本来は2-0が妥当だが、
    # 試合続行不能等の事情で1-0のまま勝敗確定として記録したいケース)が
    # 将来的に出てくる可能性がある。その場合はこの過半数チェックが
    # 邪魔になるため、将来的に緩和・無効化する対応を検討する必要が
    # あるかもしれない。現時点では常に過半数到達を必須とする。
    winning_legs = (total_legs + 1) // 2

    if max(pair1_legs, pair2_legs) < winning_legs:
        return "過半数の星に達していません。"

    return None

